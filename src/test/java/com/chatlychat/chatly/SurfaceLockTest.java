package com.chatlychat.chatly;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.EnumMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;
import java.util.function.Function;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * Executes all 163 surface methods, records the request each one actually issued, writes
 * {@code surface.lock.json}, and asserts the result equals {@code packages/sdk-spec/surface.json}.
 *
 * <h2>Why a lock, and why it is generated by running the client</h2>
 *
 * The cross-language parity gate used to match path strings in SDK <em>source text</em>. That is not
 * evidence of anything. It credited this SDK with 55/55 while two of those methods did not exist,
 * because a Javadoc paragraph explaining that two routes were broken happened to contain their
 * paths — the gate read documentation as implementation. It equally cannot see a path assembled by a
 * helper, or tell a method that issues the right path once from one that issues it twice.
 *
 * <p>This can. Every entry is reached by calling the public method, through the real
 * {@link Transport}, with a scripted sender capturing the wire. The path written to the lock is the
 * path the client produced, normalised back to the manifest's placeholder form by positional segment
 * match — so a literal segment differing by one character ({@code /v1/tickets/queue} for
 * {@code /v1/tickets/queues}) fails rather than being quietly rewritten.
 *
 * <h2>The lock is written and read by ONE test, on purpose</h2>
 *
 * The lock is both written and read by {@link #theLockIsGeneratedByExecutionAndMatchesTheManifest}.
 * Splitting the write and the read into two {@code @Test}s would be worse than it looks: JUnit's
 * default method order is deterministic but unspecified, so the reader might run first and fail on
 * a missing file — and if the writer were forced to run first, a "the committed lock is up to date"
 * reader would be comparing the just-written file against itself and would pass unconditionally.
 * That is a test that looks like evidence and is not. One method, explicit sequence.
 *
 * <p>The other two tests here touch no file. One asserts the {@link ResponseShape} column is not
 * vacuous; the other drives the ten auto-paginators with the <em>wrong</em> body and requires each
 * to throw.
 *
 * <h2>Where the response shapes come from</h2>
 *
 * Each entry also carries the top-level shape of the route's successful response, and that column
 * is <strong>hand-written in {@link ResponseShape}</strong> — read its javadoc before changing a
 * value. It is not derived from the manifest, because a fixture derived from the manifest agrees
 * with the manifest even when the manifest is wrong, which is a thing that has happened and cost
 * two other SDKs a production decode error. The gate diffs eight SDKs' independently written
 * columns against {@code surface.json}.
 *
 * <h2>It does not soft-skip</h2>
 *
 * If the manifest cannot be found, it fails. A test that reports a pass for assertions it never ran
 * is worse than a missing test, because the green line then means nothing and nobody knows it.
 */
class SurfaceLockTest {

  /**
   * The manifest's path, relative to a directory walked upwards from the working directory.
   *
   * Two spellings. The monorepo's {@code packages/sdk-spec/surface.json}, and — because a public
   * mirror has no {@code packages/} above the package — the vendored {@code sdk-spec/surface.json}
   * that {@code scripts/sync-sdk-repos.mjs} writes at the mirror root. Without the second, this
   * test could not find the manifest in any mirror, and a surface proof that cannot run is a green
   * line meaning nothing.
   */
  private static final String[] MANIFEST_CANDIDATES = {
    "packages/sdk-spec/surface.json", "sdk-spec/surface.json",
  };

  private static final String MANIFEST = "packages/sdk-spec/surface.json";

  private static final String LOCK_FILE = "surface.lock.json";

  /**
   * Below this, the manifest has stopped parsing rather than legitimately shrunk.
   *
   * <p>156, raised from 50 when the surface went from 55 routes to 159, then again at 162, and
   * again when {@code visitors.start_conversation} brought the manifest to 163. A floor
   * rather than an
   * equality because the manifest is meant to grow — but a floor set far below the real count is
   * barely a floor, and the failure it exists to catch is a run that audits a handful of entries
   * because the file stopped parsing and reports a pass for the handful it managed to read.
   */
  private static final int MANIFEST_FLOOR = 156;

  /**
   * One row of the lock, and of the manifest.
   *
   * @param shape from {@link ResponseShape} when this row describes what the client did, and from
   *     {@code surface.json} when it describes what the manifest declares. Those are two
   *     independently written facts, and {@link #describe()} puts the shape inside the comparable
   *     value so a disagreement between them fails the set diff below rather than needing its own
   *     check that somebody could forget to write.
   */
  private record Row(String ns, String name, String http, String path, String shape) {
    String id() {
      return ns + "." + name;
    }

    String describe() {
      return http + " " + path + " \u2192 " + shape + "  (" + id() + ")";
    }
  }

  @Test
  @DisplayName("executing all 163 methods reproduces the manifest, and writes surface.lock.json")
  void theLockIsGeneratedByExecutionAndMatchesTheManifest() throws IOException {

    // 1. the manifest, which is the only authority for ns, name, verb and path
    Path repoRoot = findRepoRoot();
    List<Row> declared =
        readManifest(Json.parseObject(Files.readString(manifestIn(repoRoot))));

    Map<String, Row> declaredById = new LinkedHashMap<>();
    for (Row row : declared) {
      if (declaredById.put(row.id(), row) != null) {
        fail("the manifest declares " + row.id() + " twice");
      }
    }

    // 2. execute every method and record what it put on the wire
    List<Row> observed = new ArrayList<>();
    List<String> problems = new ArrayList<>();

    for (SurfaceCalls.Entry entry : SurfaceCalls.all()) {
      Row expected = declaredById.get(entry.id());
      if (expected == null) {
        problems.add(entry.id() + " is implemented here but is not in the manifest");
        continue;
      }
      try {
        SurfaceCalls.Issued issued = SurfaceCalls.execute(entry);
        // The template comes from the MANIFEST, not from this test's own copy of
        // it, so there is a single authority for the placeholder names and the
        // test cannot quietly agree with itself about a path the manifest
        // disagrees with.
        String normalised = SurfaceCalls.normalise(issued.path(), expected.path(), entry.id());
        if (!issued.method().equals(expected.http())) {
          problems.add(
              entry.id() + " issued " + issued.method() + ", manifest declares " + expected.http());
          continue;
        }
        /*
         * The value the method handed back really has the shape this SDK
         * declared for the route.
         *
         * This is what catches a method that wraps or unwraps even when the
         * request it issued was perfect: a `list` that returned `page.items()`
         * from a page route, or one that reached for `items` on a bare-array
         * route, disagrees here. `SurfaceCalls.execute` fed it the body of its
         * OWN declared shape, so the declaration is load-bearing in both
         * directions.
         */
        ResponseShape shape = entry.shape();
        String actual = ResponseShape.actual(issued.value());
        if (!shape.wire().equals(actual)) {
          problems.add(
              entry.id()
                  + " is declared "
                  + shape.wire()
                  + " but handed back "
                  + actual
                  + " ("
                  + (issued.value() == null ? "null" : issued.value().getClass().getName())
                  + ")");
          continue;
        }
        observed.add(new Row(entry.ns(), entry.name(), issued.method(), normalised, shape.wire()));
      } catch (AssertionError e) {
        problems.add(e.getMessage());
      }
    }

    observed.sort(Comparator.comparing(Row::ns).thenComparing(Row::name));

    // 3. read what is committed, then overwrite it with what this run observed.
    //    Written before the assertions on purpose: the lock records what the code
    //    does, and leaving a stale one behind after a failing run would make the
    //    artifact disagree with the code exactly when somebody is reading it to
    //    find out why.
    Path lockPath = Paths.get(System.getProperty("user.dir")).resolve(LOCK_FILE);
    String committed = Files.exists(lockPath) ? Files.readString(lockPath) : null;
    String regenerated = renderLock(observed);
    Files.writeString(lockPath, regenerated, StandardCharsets.UTF_8);

    // 4. did any method fail to issue what the manifest declares?
    if (!problems.isEmpty()) {
      fail(
          "surface lock: "
              + problems.size()
              + " problem(s) while executing the surface:\n  "
              + String.join("\n  ", problems));
    }

    // 5. is the set of executed routes exactly the manifest's set?
    TreeSet<String> declaredSet = new TreeSet<>();
    declared.forEach(r -> declaredSet.add(r.describe()));
    TreeSet<String> observedSet = new TreeSet<>();
    observed.forEach(r -> observedSet.add(r.describe()));

    if (!declaredSet.equals(observedSet)) {
      TreeSet<String> missing = new TreeSet<>(declaredSet);
      missing.removeAll(observedSet);
      TreeSet<String> extra = new TreeSet<>(observedSet);
      extra.removeAll(declaredSet);
      StringBuilder sb = new StringBuilder("surface.lock.json does not equal the manifest.\n");
      if (!missing.isEmpty()) {
        sb.append("  declared in the manifest, issued by no method:\n");
        missing.forEach(m -> sb.append("    ").append(m).append('\n'));
      }
      if (!extra.isEmpty()) {
        sb.append("  issued by a method, declared in no manifest entry:\n");
        extra.forEach(m -> sb.append("    ").append(m).append('\n'));
      }
      fail(sb.toString());
    }

    assertEquals(
        declared.size(),
        observed.size(),
        "every manifest entry must be covered exactly once by an executed method");

    // 6. the lock parses, and says which SDK produced it and how
    Map<String, Object> parsed = Json.parseObject(regenerated);
    assertEquals("java", parsed.get("sdk"));
    assertEquals(
        "src/test/java/com/chatlychat/chatly/SurfaceLockTest.java", parsed.get("generatedBy"));
    assertTrue(parsed.get("entries") instanceof List, "entries must be a JSON array");
    assertEquals(declared.size(), ((List<?>) parsed.get("entries")).size());

    // 7. finally: was the committed lock already correct?
    //    This is the check that makes the committed file worth anything to a
    //    reviewer who has not run the tests. It is last so that a genuine
    //    surface change reports the *interesting* failure above first.
    if (committed != null && !committed.equals(regenerated)) {
      fail(
          LOCK_FILE
              + " was stale and has just been rewritten by this run. The surface changed;"
              + " commit the updated file. (It is a committed artifact, not a build output —"
              + " that is what lets a reviewer see a surface change in the diff.)");
    }
  }

  /**
   * The shape column is not vacuous: every route has one, and the distribution is the real one.
   *
   * <p>A column that said {@code object} 163 times would satisfy every other assertion in this file
   * — each method would be fed {@code {"id":"x_1"}}, each would hand back a {@code Map}, and the
   * green line would mean nothing at all. That failure mode is not hypothetical in this repository:
   * twice now the number in a gate's green line has been the number of rows it managed to parse
   * rather than the number that exist. So the distribution is pinned.
   *
   * <p>33 / 13 / 116 / 1, from reading all 163 {@code @ZodResponse} schemas in
   * {@code apps/api/src} — 14 / 10 / 30 / 1 over the first 55 on 2026-10-12, 104 more on
   * 2026-10-14, and then {@code root.me} (a discriminated union of two objects),
   * {@code webhooks.delete} (an object, not the 204 its verb suggests) and
   * {@code workspace.mine} (a bare array). {@code visitors.start_conversation} took {@code object}
   * to 116 on 2026-10-14, and it is the one row on the surface with no {@code @ZodResponse} to
   * read: its shape comes off the declared return type of the service its handler forwards to.
   * If the surface grows these change — but all four values must stay represented,
   * and {@code empty} must stay at exactly one until a second real 204 ships, because
   * {@code empty} is the only value that proves the fake can withhold a body.
   */
  @Test
  @DisplayName("every route has a hand-declared shape, and the four values are really distributed")
  void theDeclaredShapeColumnCoversTheSurfaceAndIsNotVacuous() {
    TreeSet<String> surfaceIds = new TreeSet<>();
    for (SurfaceCalls.Entry entry : SurfaceCalls.all()) {
      surfaceIds.add(entry.id());
    }
    assertEquals(
        surfaceIds,
        new TreeSet<>(ResponseShape.declared().keySet()),
        "ResponseShape must declare a shape for exactly the routes this SDK implements — a route"
            + " with no declaration, or a declaration for a route that no longer exists, is a"
            + " column drifting away from the code it is supposed to describe");

    EnumMap<ResponseShape, Integer> counts = new EnumMap<>(ResponseShape.class);
    for (ResponseShape shape : ResponseShape.values()) {
      counts.put(shape, 0);
    }
    for (ResponseShape shape : ResponseShape.declared().values()) {
      counts.merge(shape, 1, Integer::sum);
    }

    EnumMap<ResponseShape, Integer> expected = new EnumMap<>(ResponseShape.class);
    expected.put(ResponseShape.ARRAY, 33);
    expected.put(ResponseShape.PAGE, 13);
    expected.put(ResponseShape.OBJECT, 116);
    expected.put(ResponseShape.EMPTY, 1);

    assertEquals(
        expected,
        counts,
        "the declared shape distribution changed. If the surface really changed, update this"
            + " expectation and the manifest in the same commit; if it did not, the column has"
            + " been flattened — which would leave every other assertion here passing for"
            + " nothing.");

    // And the four bodies really are four different things. A fixture set where
    // `empty` quietly became `{}` would make the 204 case indistinguishable
    // from an object, which is the one distinction this value exists to make.
    assertEquals(204, ResponseShape.EMPTY.status(), "the empty shape must be a real 204");
    assertEquals(null, ResponseShape.EMPTY.body(), "a 204 carries no body, not an empty one");
    for (ResponseShape shape : ResponseShape.values()) {
      if (shape != ResponseShape.EMPTY) {
        assertEquals(200, shape.status(), shape.wire() + " is answered with a 200");
        assertTrue(shape.body() != null && !shape.body().isEmpty(), shape.wire() + " needs a body");
      }
    }
    /*
     * The one per-route body override, bounded.
     *
     * `SurfaceCalls.SCALAR_ARRAY_BODIES` exists for `channels.adapters`, whose
     * array holds strings. It is the crack through which a per-route body table
     * could grow back — and a per-route body table is what made the fixture and
     * the route's real shape two hand-synchronised facts in the first place. So:
     * exactly one entry, and its declared shape must be ARRAY, because an
     * override on a `page` or `object` row would be feeding a method a body of
     * a shape nobody declared.
     */
    assertEquals(
        1,
        SurfaceCalls.SCALAR_ARRAY_BODIES.size(),
        "only channels.adapters may override its body; see SurfaceCalls.SCALAR_ARRAY_BODIES");
    SurfaceCalls.SCALAR_ARRAY_BODIES
        .keySet()
        .forEach(
            id ->
                assertEquals(
                    ResponseShape.ARRAY,
                    ResponseShape.of(id),
                    id + " overrides its body, so it must be declared `array`"));

    assertEquals(
        ResponseShape.values().length,
        new TreeSet<>(
                List.of(
                    String.valueOf(ResponseShape.ARRAY.body()),
                    String.valueOf(ResponseShape.PAGE.body()),
                    String.valueOf(ResponseShape.OBJECT.body()),
                    String.valueOf(ResponseShape.EMPTY.body())))
            .size(),
        "the four fixture bodies must be four distinct things");
  }

  /**
   * The negative direction: every auto-paginator fed a bare array must fail loudly.
   *
   * <p>The test above proves each method copes with the shape this SDK says the route sends. It
   * cannot prove the declaration <em>matters</em> — a decoder that ignored the body entirely would
   * pass it, and so would one that turned anything unrecognised into an empty page. That second one
   * is not a straw man: the Rust client's derived {@code Page} deserializer read a bare array as an
   * <em>empty page</em> and returned it with a 200, which is a wrong answer rather than a missing
   * error, and a caller walking it would conclude the list was empty.
   *
   * <p>So this feeds all thirteen walkers {@code [{"id":"x_1"}]} where they expect
   * {@code {items, nextCursor}} and requires each to throw. {@link Page#fromDecoded} is the place
   * that must refuse it.
   */
  @Test
  @DisplayName("every auto-paginator rejects a bare array where a page envelope is expected")
  void everyAutoPaginatorRejectsABareArray() {
    Map<String, Function<Chatly, Pager<Map<String, Object>>>> walkers = SurfaceCalls.pagers();

    /*
     * The set of walkers is exactly the set of routes THIS SDK declares `page`,
     * so the test cannot quietly shrink to nothing while still reporting a
     * pass. Derived from ResponseShape rather than from the manifest's `paged`
     * flag on purpose — ListShapeTest already checks the same map against the
     * manifest, and two authorities pointed at one map is the point.
     */
    TreeSet<String> pageRoutes = new TreeSet<>();
    ResponseShape.declared()
        .forEach(
            (id, shape) -> {
              if (shape == ResponseShape.PAGE) {
                pageRoutes.add(id);
              }
            });
    assertEquals(
        pageRoutes,
        new TreeSet<>(walkers.keySet()),
        "one walker per `page` route and nothing else");
    assertEquals(
        13, pageRoutes.size(), "thirteen page routes — the floor that stops this test shrinking");

    List<String> accepted = new ArrayList<>();
    for (Map.Entry<String, Function<Chatly, Pager<Map<String, Object>>>> walker :
        walkers.entrySet()) {
      FakeSender sender = new FakeSender().then(200, ResponseShape.ARRAY.body());
      try {
        // hasNext() is what triggers the first fetch; a Pager is lazy, so
        // merely building one proves nothing.
        walker.getValue().apply(sender.client()).iterator().hasNext();
        accepted.add(walker.getKey());
      } catch (RuntimeException expected) {
        // The required outcome. A bare array is not a page.
      }
    }

    if (!accepted.isEmpty()) {
      fail(
          accepted.size()
              + " paginator(s) accepted a bare array as a page envelope instead of throwing:\n  "
              + String.join("\n  ", accepted)
              + "\nThat is the Rust client's bug: a non-page body read as an empty page is a wrong"
              + " answer with a 200, not a missing error.");
    }
  }

  // --------------------------------------------------------------- helpers

  @SuppressWarnings("unchecked") // the manifest's shape is checked as it is read
  private static List<Row> readManifest(Map<String, Object> manifest) {
    if (!(manifest.get("entries") instanceof List<?> list)) {
      throw new AssertionError(MANIFEST + " has no `entries` array");
    }
    List<Row> out = new ArrayList<>();
    for (Object raw : list) {
      if (!(raw instanceof Map)) {
        throw new AssertionError(MANIFEST + " has a non-object in `entries`");
      }
      Map<String, Object> e = (Map<String, Object>) raw;
      out.add(
          new Row(
              (String) e.get("ns"),
              (String) e.get("name"),
              (String) e.get("http"),
              (String) e.get("path"),
              (String) e.get("shape")));
    }
    // A floor, not an equality. The manifest is meant to grow; what must never
    // happen is a run that audits three entries because the file stopped
    // parsing and reports a pass for the three it managed to read.
    if (out.size() < MANIFEST_FLOOR) {
      throw new AssertionError(
          MANIFEST
              + " yielded only "
              + out.size()
              + " entries, floor is "
              + MANIFEST_FLOOR
              + " — it has stopped parsing correctly, or the surface shrank and this floor needs"
              + " lowering in the same commit.");
    }
    return out;
  }

  /** The lock, rendered byte-for-byte deterministically so that any diff is a real change. */
  private static String renderLock(List<Row> rows) {
    StringBuilder sb = new StringBuilder();
    sb.append("{\n");
    sb.append("  \"sdk\": \"java\",\n");
    sb.append("  \"generatedBy\": \"src/test/java/com/chatlychat/chatly/SurfaceLockTest.java\",\n");
    sb.append("  \"entries\": [\n");
    for (int i = 0; i < rows.size(); i++) {
      Row r = rows.get(i);
      sb.append("    { \"ns\": ")
          .append(Json.write(r.ns()))
          .append(", \"name\": ")
          .append(Json.write(r.name()))
          .append(", \"http\": ")
          .append(Json.write(r.http()))
          .append(", \"path\": ")
          .append(Json.write(r.path()))
          .append(", \"shape\": ")
          .append(Json.write(r.shape()))
          .append(" }");
      if (i < rows.size() - 1) {
        sb.append(',');
      }
      sb.append('\n');
    }
    sb.append("  ]\n");
    sb.append("}\n");
    return sb.toString();
  }

  /** Whichever of {@link #MANIFEST_CANDIDATES} exists under {@code root}. */
  private static Path manifestIn(Path root) {
    for (String candidate : MANIFEST_CANDIDATES) {
      Path p = root.resolve(candidate);
      if (Files.exists(p)) {
        return p;
      }
    }
    return root.resolve(MANIFEST);
  }

  /**
   * Walk up from the working directory looking for the manifest.
   *
   * <p>Not a hardcoded {@code ../../}: surefire's working directory is the module, but a developer
   * running one test from an IDE may be rooted anywhere, and a relative path that resolves in one
   * and not the other is a test that fails for reasons unrelated to the code.
   */
  private static Path findRepoRoot() {
    Path dir = Paths.get(System.getProperty("user.dir")).toAbsolutePath();
    for (Path p = dir; p != null; p = p.getParent()) {
      for (String candidate : MANIFEST_CANDIDATES) {
        if (Files.exists(p.resolve(candidate))) {
          return p;
        }
      }
    }
    throw new UncheckedIOException(
        new IOException(
            "could not find "
                + MANIFEST
                + " in any ancestor of "
                + dir
                + ". This test asserts the SDK against the shared manifest and cannot run without"
                + " it; it fails rather than skipping, because a skipped parity check that reports"
                + " a pass is worse than no check at all."));
  }
}
